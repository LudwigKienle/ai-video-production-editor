#!/usr/bin/env node
/**
 * Converts the brand fonts (OFL, npm @fontsource) into outline data for the
 * logo: src/brand/brandGlyphs.generated.ts. The SVGs, the canvas splash and
 * the icons then draw text as paths; no font is embedded or loaded at runtime.
 *
 *   node scripts/brand/build-glyphs.mjs
 */
import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const opentype = require('opentype.js');
const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');

const FONTS = {
  serif: { file: '@fontsource/cormorant-garamond/files/cormorant-garamond-latin-600-normal.woff', family: 'Cormorant Garamond 600' },
  sans: { file: '@fontsource/jost/files/jost-latin-500-normal.woff', family: 'Jost 500' },
};
const CHARS = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789&.-·';

const round = (n) => Math.round(n * 10) / 10;

const pathToD = (path) => path.commands.map((c) => {
  switch (c.type) {
    case 'M': return `M${round(c.x)} ${round(c.y)}`;
    case 'L': return `L${round(c.x)} ${round(c.y)}`;
    case 'Q': return `Q${round(c.x1)} ${round(c.y1)} ${round(c.x)} ${round(c.y)}`;
    case 'C': return `C${round(c.x1)} ${round(c.y1)} ${round(c.x2)} ${round(c.y2)} ${round(c.x)} ${round(c.y)}`;
    case 'Z': return 'Z';
    default: return '';
  }
}).join('');

const out = {};
for (const [key, spec] of Object.entries(FONTS)) {
  const font = opentype.loadSync(require.resolve(spec.file));
  const upm = font.unitsPerEm;
  const os2 = font.tables.os2 || {};
  const capHeight = os2.sCapHeight || font.charToGlyph('H').getBoundingBox().y2;
  const glyphs = {};
  for (const ch of CHARS) {
    const glyph = font.charToGlyph(ch);
    if (!glyph || glyph.index === 0) continue;
    // fontSize = unitsPerEm -> coordinates in font units, y down, baseline at 0.
    const d = pathToD(glyph.getPath(0, 0, upm));
    glyphs[ch] = { d, adv: round(glyph.advanceWidth) };
  }
  const space = font.charToGlyph(' ');
  out[key] = { family: spec.family, license: 'SIL Open Font License 1.1', unitsPerEm: upm, capHeight, space: round(space.advanceWidth), glyphs };
}

const header = `/* eslint-disable */
// GENERATED by scripts/brand/build-glyphs.mjs - do not edit by hand.
// Outlines of OFL fonts from npm @fontsource (Cormorant Garamond 600, Jost 500),
// in font units, y axis down, baseline at y = 0.
`;
const body = `export type BrandGlyph = { d: string; adv: number };
export type BrandGlyphSet = { family: string; license: string; unitsPerEm: number; capHeight: number; space: number; glyphs: Record<string, BrandGlyph> };

export const BRAND_GLYPHS: { serif: BrandGlyphSet; sans: BrandGlyphSet } = ${JSON.stringify(out, null, 1)};
`;
const target = join(root, 'src', 'brand', 'brandGlyphs.generated.ts');
writeFileSync(target, header + body);
console.log(`wrote ${target.replace(root + '/', '')} (${Object.keys(out.serif.glyphs).length}+${Object.keys(out.sans.glyphs).length} glyphs)`);
